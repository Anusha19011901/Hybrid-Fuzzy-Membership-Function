"""Binary Brain Storm Optimization (BBSO) for attribute selection.

Brain Storm Optimization (Shi, 2011) mimics a brainstorming session: ideas
(candidate solutions) are clustered, new ideas are generated by perturbing a
cluster centre or a random idea, or by merging ideas from two clusters, and a
new idea replaces the one it was generated from if it scores better. The
binary variant keeps a real-valued position per idea and turns it into a
0/1 mask with a sigmoid transfer function.

Here one idea is a mask over the 13 *clinical attributes* (not the 22
encoded columns): an attribute is kept or dropped together with every column
it produced. Fitness is supplied by the caller; in this project it is the
macro F1 of logistic regression under an inner stratified CV on the training
split (see :class:`MaskFitness`).

The algorithm is stochastic. Every run takes a seed and is reproducible for
that seed; the phase 3 script runs ten seeds and reports selection frequency.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Callable

import numpy as np
import pandas as pd
from sklearn.cluster import KMeans
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import f1_score
from sklearn.model_selection import StratifiedKFold

from hfm import config
from hfm.preprocess import build_preprocessor, columns_for_attributes, transform_to_frame


def sigmoid(x: np.ndarray) -> np.ndarray:
    return 1.0 / (1.0 + np.exp(-x))


# --------------------------------------------------------------------------- #
# Fitness: inner-CV macro F1 of a light classifier, memoised per mask
# --------------------------------------------------------------------------- #
class MaskFitness:
    """Macro F1 of logistic regression for an attribute mask, under inner CV.

    Preprocessing is attribute-wise (each column's imputation and scaling
    depends only on that column), so it is fitted once per inner fold on the
    fold's training rows and reused for every mask. Each mask then costs one
    logistic-regression fit per fold. Results are cached by mask, so repeated
    masks (common once the search converges) are free; the cache can be
    shared across seeds because the fitness is a deterministic function of
    the mask.
    """

    def __init__(
        self,
        X: pd.DataFrame,
        y: pd.Series,
        attributes: list[str] | None = None,
        n_splits: int = 3,
        seed: int = config.SEED,
        C: float = 1.0,
    ):
        self.attributes = list(config.FEATURE_COLS if attributes is None else attributes)
        self.C = C
        self.n_evals = 0
        self.cache: dict[bytes, float] = {}
        y = np.asarray(y)
        cv = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=seed)
        self.folds = []
        for tr, va in cv.split(X, y):
            pre = build_preprocessor(scaler="standard").fit(X.iloc[tr])
            self.folds.append((pre, transform_to_frame(pre, X.iloc[tr]), y[tr],
                               transform_to_frame(pre, X.iloc[va]), y[va]))

    @property
    def n_features(self) -> int:
        return len(self.attributes)

    def selected(self, mask: np.ndarray) -> list[str]:
        return [a for a, m in zip(self.attributes, mask) if m]

    def __call__(self, mask: np.ndarray) -> float:
        mask = np.asarray(mask, dtype=bool)
        key = np.packbits(mask).tobytes()
        if key in self.cache:
            return self.cache[key]
        if not mask.any():
            score = 0.0
        else:
            attrs = self.selected(mask)
            scores = []
            for pre, Xtr, ytr, Xva, yva in self.folds:
                cols = columns_for_attributes(pre, attrs)
                clf = LogisticRegression(max_iter=2000, C=self.C).fit(Xtr[cols], ytr)
                scores.append(f1_score(yva, clf.predict(Xva[cols]), average="macro", zero_division=0))
            score = float(np.mean(scores))
            self.n_evals += 1
        self.cache[key] = score
        return score


# --------------------------------------------------------------------------- #
# The optimiser
# --------------------------------------------------------------------------- #
@dataclass
class BBSOConfig:
    n_pop: int = 20            # ideas in the population
    n_clusters: int = 3        # k-means clusters per iteration
    max_iter: int = 50
    patience: int = 12         # stop after this many iterations without improvement
    p_replace_center: float = 0.2   # chance per iteration to replace a centre with a random idea
    p_one_cluster: float = 0.8      # generate from one cluster (else merge two)
    p_center: float = 0.4           # within one cluster: use the centre (else a random member)
    p_center_pair: float = 0.5      # when merging: use both centres (else random members)
    slope: float = 20.0             # k in the step-size schedule logsig((T/2 - t) / k)
    init_scale: float = 1.0         # positions start ~ N(0, init_scale)
    anchor: float = 1.5             # after sampling a mask, |x_j| >= anchor with sign(x_j) = bit j


@dataclass
class BBSOResult:
    best_mask: np.ndarray
    best_fitness: float
    history: list[float]            # best fitness after each iteration
    n_iter: int
    stopped_early: bool
    seed: int
    population: list[tuple[np.ndarray, float]] = field(default_factory=list)


class BBSO:
    """Binary Brain Storm Optimization over fixed-length 0/1 masks."""

    def __init__(self, fitness: Callable[[np.ndarray], float], n_features: int,
                 cfg: BBSOConfig | None = None, seed: int = config.SEED):
        self.fitness = fitness
        self.n_features = n_features
        self.cfg = BBSOConfig() if cfg is None else cfg
        self.seed = seed
        self.rng = np.random.default_rng(seed)

    # ---- helpers --------------------------------------------------------- #
    def _binarise(self, x: np.ndarray) -> np.ndarray:
        """Sigmoid transfer: bit j is 1 with probability sigmoid(x_j). Never all-zero."""
        mask = self.rng.random(len(x)) < sigmoid(x)
        if not mask.any():
            mask[self.rng.integers(len(x))] = True
        return mask

    def _evaluate(self, x: np.ndarray) -> tuple[np.ndarray, float]:
        """Sample a mask from x, score it, and anchor x to the sampled mask.

        Anchoring (sign of x_j = bit j, |x_j| >= anchor) makes the position a
        faithful encoding of the idea it scored, so a child of a good idea
        inherits most of its bits: sigmoid(1.5) = 0.82 keeps each bit with
        probability 0.82 before the step noise is added. Without it, the
        stochastic transfer re-rolls every bit and good masks do not persist.
        """
        mask = self._binarise(x)
        x[:] = np.where(mask, 1.0, -1.0) * np.maximum(np.abs(x), self.cfg.anchor)
        return mask, self.fitness(mask)

    def _step_size(self, t: int) -> float:
        c = self.cfg
        return sigmoid((0.5 * c.max_iter - t) / c.slope) * self.rng.random()

    def _cluster(self, X: np.ndarray, fit: np.ndarray) -> tuple[np.ndarray, list[int]]:
        """k-means on positions; the centre of a cluster is its fittest member."""
        k = min(self.cfg.n_clusters, len(X))
        labels = KMeans(n_clusters=k, n_init=1, random_state=int(self.rng.integers(2**31))).fit_predict(X)
        centers = []
        for c in range(k):
            members = np.flatnonzero(labels == c)
            if len(members) == 0:             # k-means can return an empty cluster
                members = np.arange(len(X))
            centers.append(int(members[np.argmax(fit[members])]))
        return labels, centers

    # ---- main loop ------------------------------------------------------- #
    def run(self) -> BBSOResult:
        c = self.cfg
        X = self.rng.normal(0, c.init_scale, size=(c.n_pop, self.n_features))
        masks = np.zeros((c.n_pop, self.n_features), dtype=bool)
        fit = np.zeros(c.n_pop)
        for i in range(c.n_pop):
            masks[i], fit[i] = self._evaluate(X[i])

        best_i = int(np.argmax(fit))
        best_mask, best_fit = masks[best_i].copy(), float(fit[best_i])
        history, stale, stopped_early, t = [], 0, False, 0

        for t in range(1, c.max_iter + 1):
            labels, centers = self._cluster(X, fit)

            # Occasionally replace a centre with a brand-new random idea (exploration).
            if self.rng.random() < c.p_replace_center:
                j = centers[self.rng.integers(len(centers))]
                X[j] = self.rng.normal(0, c.init_scale, size=self.n_features)
                masks[j], fit[j] = self._evaluate(X[j])

            for i in range(c.n_pop):
                if self.rng.random() < c.p_one_cluster:
                    k = self.rng.integers(len(centers))
                    if self.rng.random() < c.p_center:
                        src = centers[k]
                    else:
                        members = np.flatnonzero(labels == k)
                        src = int(self.rng.choice(members)) if len(members) else centers[k]
                    base = X[src]
                else:
                    k1, k2 = self.rng.choice(len(centers), size=2, replace=len(centers) < 2)
                    if self.rng.random() < c.p_center_pair:
                        a, b = X[centers[k1]], X[centers[k2]]
                    else:
                        m1, m2 = np.flatnonzero(labels == k1), np.flatnonzero(labels == k2)
                        a = X[int(self.rng.choice(m1))] if len(m1) else X[centers[k1]]
                        b = X[int(self.rng.choice(m2))] if len(m2) else X[centers[k2]]
                    r = self.rng.random()
                    base = r * a + (1 - r) * b
                    src = i
                x_new = base + self._step_size(t) * self.rng.normal(size=self.n_features)
                m_new, f_new = self._evaluate(x_new)
                # Greedy replacement of the idea that was perturbed.
                if f_new > fit[src] or (f_new == fit[src] and m_new.sum() < masks[src].sum()):
                    X[src], masks[src], fit[src] = x_new, m_new, f_new

            i_best = int(np.argmax(fit))
            if fit[i_best] > best_fit:
                best_fit, best_mask, stale = float(fit[i_best]), masks[i_best].copy(), 0
            else:
                stale += 1
            history.append(best_fit)
            if stale >= c.patience:
                stopped_early = True
                break

        return BBSOResult(best_mask, best_fit, history, t, stopped_early, self.seed,
                          [(masks[i].copy(), float(fit[i])) for i in range(c.n_pop)])


# --------------------------------------------------------------------------- #
# Multi-seed summary
# --------------------------------------------------------------------------- #
def selection_frequency(results: list[BBSOResult], attributes: list[str]) -> pd.Series:
    """Fraction of runs whose best mask includes each attribute."""
    stack = np.vstack([r.best_mask for r in results])
    return pd.Series(stack.mean(axis=0), index=attributes, name="frequency").sort_values(ascending=False)


def consensus_subset(results: list[BBSOResult], attributes: list[str],
                     threshold: float = 0.5) -> tuple[list[str], str]:
    """The subset to carry forward, and how it was chosen.

    The most frequent best mask across seeds wins. If every seed found a
    different mask, fall back to the attributes selected in at least
    ``threshold`` of the runs.
    """
    keys = [tuple(r.best_mask.tolist()) for r in results]
    counts = pd.Series(keys).value_counts()
    if counts.iloc[0] > 1:
        best_key = max(counts[counts == counts.iloc[0]].index,
                       key=lambda k: max(r.best_fitness for r, kk in zip(results, keys) if kk == k))
        return [a for a, m in zip(attributes, best_key) if m], f"modal best mask ({counts.iloc[0]} of {len(results)} seeds)"
    freq = selection_frequency(results, attributes)
    return [a for a in attributes if freq[a] >= threshold], f"attributes selected in >= {threshold:.0%} of seeds"
